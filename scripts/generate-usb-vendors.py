#!/usr/bin/env python3
"""Generate Bus Stop's USB vendor-name table from the USB ID Repository.

Usage:
    scripts/generate-usb-vendors.py path/to/usb.ids [output.swift]

Reads usb.ids from the USB ID Repository (http://www.linux-usb.org/usb.ids,
dual-licensed under the GPL version 2 or later or the 3-clause BSD License;
Bus Stop uses it under the 3-clause BSD License) and writes
Sources/BusStopCore/Labels/USBVendorCatalog+Data.swift: one row per vendor,
sorted by vendor ID. Products, interfaces and the class and HID tables that
follow the vendor list are left out to keep the table small.

The output is deterministic: the same input always produces the same bytes.
It uses only the Python standard library, and it reads a file you have
downloaded: Bus Stop itself never fetches the list.

Vendor names are kept as usb.ids writes them, except that control characters
are removed and surrounding whitespace is trimmed.
"""

import os
import re
import sys
import unicodedata

SOURCE_URL = "http://www.linux-usb.org/usb.ids"
SOURCE_LICENSE = "Used under the 3-clause BSD License"

# A vendor line: four lowercase hex digits at column 0, two spaces, the name.
VENDOR_LINE = re.compile(rb"^([0-9a-f]{4})  (.*)$")
# The first line of the sections after the vendor list ("C 00  ...").
SECTION_LINE = re.compile(rb"^[A-Z]+ ")
VERSION_LINE = re.compile(rb"^#\s*Version:\s*(\S.*?)\s*$")
DATE_LINE = re.compile(rb"^#\s*Date:\s*(\S.*?)\s*$")

DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    os.pardir,
    "Sources",
    "BusStopCore",
    "Labels",
    "USBVendorCatalog+Data.swift",
)


def fail(message):
    sys.stderr.write("generate-usb-vendors: " + message + "\n")
    sys.exit(1)


def swift_string(value):
    """A Swift string literal for `value`, escaping what Swift requires."""
    out = []
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7F:
            out.append("\\u{%X}" % code)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def clean_name(value):
    """`value` without control characters and surrounding whitespace."""
    return "".join(ch for ch in value if unicodedata.category(ch) != "Cc").strip()


def load_vendors(path):
    # Read bytes: the HID tables after the vendor list are not all valid
    # UTF-8, so only the lines that are used get decoded.
    try:
        with open(path, "rb") as handle:
            raw_lines = handle.read().split(b"\n")
    except OSError as error:
        fail("cannot read %s: %s" % (path, error))

    version = None
    date = None
    vendors = {}
    for number, line in enumerate(raw_lines, start=1):
        line = line.rstrip(b"\r")
        if SECTION_LINE.match(line):
            break
        if line.startswith(b"#"):
            if version is None and VERSION_LINE.match(line):
                version = VERSION_LINE.match(line).group(1).decode("ascii", "replace")
            elif date is None and DATE_LINE.match(line):
                date = DATE_LINE.match(line).group(1).decode("ascii", "replace")
            continue
        match = VENDOR_LINE.match(line)
        if not match:
            continue
        where = "line %d" % number
        try:
            name = clean_name(match.group(2).decode("utf-8"))
        except UnicodeDecodeError:
            fail(where + ": vendor name is not valid UTF-8")
        if not name:
            fail(where + ": vendor name is empty")
        vendor_id = int(match.group(1), 16)
        if vendor_id in vendors:
            fail("%s duplicates vendor %04x" % (where, vendor_id))
        vendors[vendor_id] = name

    if version is None:
        fail("no '# Version:' line in the header")
    if date is None:
        fail("no '# Date:' line in the header")
    if not vendors:
        fail("no vendors found")
    return version, date, sorted(vendors.items())


def render(version, date, vendors):
    lines = [
        "// USB vendor names by vendor ID.",
        "//",
        "// Source: the USB ID Repository, %s" % SOURCE_URL,
        "// Version %s (%s)." % (version, date),
        "// %s. See THIRD_PARTY_NOTICES.md." % SOURCE_LICENSE,
        "//",
        "// Generated by scripts/generate-usb-vendors.py. Do not edit by hand.",
        "//",
        "// %d vendors. Products are left out." % len(vendors),
        "",
        "extension USBVendorCatalog {",
        "    /// Every vendor, sorted by vendor ID.",
        "    static let generatedVendors: [(id: Int, name: String)] = [",
    ]
    for vendor_id, name in vendors:
        lines.append("        (0x%04X, %s)," % (vendor_id, swift_string(name)))
    lines += [
        "    ]",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    if len(argv) not in (2, 3) or argv[1] in ("-h", "--help"):
        sys.stderr.write(__doc__)
        return 2 if len(argv) not in (2, 3) else 0
    version, date, vendors = load_vendors(argv[1])
    output = argv[2] if len(argv) == 3 else os.path.normpath(DEFAULT_OUTPUT)
    text = render(version, date, vendors)
    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    sys.stdout.write("Wrote %d vendors (usb.ids %s) to %s\n" % (len(vendors), version, output))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
